-- Writes protocol/bridge_vectors.json from the addon's own BF2 encoder.
--   luajit tools/gen_bridge_vectors.lua [out.json]
-- The Python client's decoder and encoder are tested against this file, so a change to Frame.lua that
-- is not mirrored in eqvoice_client/bridge/frame.py fails a test instead of failing in game.

local here = arg[0]:gsub("[/\\][^/\\]*$", "")
local addon = here .. "/../eqvoice-addon/EqVoice/"
local out = arg[1] or (here .. "/../protocol/bridge_vectors.json")

GetTime = function() return 0 end
dofile(addon .. "Util.lua")
dofile(addon .. "Frame.lua")
local OV, F = EqVoice, EqVoice.Frame

local function r(name, dist, flags) return { name = name, dist = dist, flags = flags } end

local function base(t)
	local s = { counter = 0, flags = 1 + 2 + 8 + 32, loginId = 1, wall = 1760000000, ack = 0, rosterSize = 0,
		checked = 0, loaded = 0, misses = 0, intervalMs = 500, cost = 0, character = "Alice", realm = "Turtle", results = {} }
	for k, v in pairs(t) do s[k] = v end
	return s
end

local many = {}
for i = 1, 60 do many[i] = r("Player" .. i, i * 0.5, 1) end
local crowd = {}
for i = 1, 40 do crowd[i] = r("Crowd" .. string.format("%02d", i), 5 + i * 0.75, 1) end

local vectors = {
	{ name = "empty", state = base({}) },
	{ name = "one_result", state = base({ counter = 1, loginId = 4000000000, ack = 7, rosterSize = 12, checked = 12, loaded = 1, misses = 11,
		results = { r("Bob", 18.4, 1) } }) },
	{ name = "wraps_and_caps", state = base({ counter = 65535, flags = 255, wall = 4294967295, ack = 65535, rosterSize = 65535,
		checked = 255, loaded = 255, misses = 255, intervalMs = 65535, cost = 65535,
		results = { r("Far", 500, 3), r("Edge", 127, 1), r("Zero", 0, 0) } }) },
	{ name = "utf8_names", state = base({ character = "\195\169mile", realm = "Cr\195\169ole",
		results = { r("\195\169lise", 3.5, 1), r("Zo\195\171", 9.25, 2) } }) },
	{ name = "dirty_names", state = base({ character = "Al ice", results = { r("A\1B C,D", 1, 1), r("", 2, 1), r("Ok", 3, 1) } }) },
	{ name = "logout", state = base({ flags = 1 + 16, results = {} }) },
	{ name = "optical_fit", state = base({ results = { r("Bob", 18.4, 1), r("Carol", 33, 1), r("Dave", 40.5, 1) } }), max = F.OPTICAL_MAX },
	{ name = "optical_truncated", state = base({ results = many }), max = F.OPTICAL_MAX },
	{ name = "crowd_file_only", state = base({ rosterSize = 500, checked = 80, loaded = 40, misses = 40, results = crowd }) },
}

local function jstr(s) return '"' .. s .. '"' end
local function ints(t, n)
	local p = {}
	for i = 1, n do p[i] = tostring(t[i]) end
	return "[" .. table.concat(p, ",") .. "]"
end

local lines = {}
for i = 1, table.getn(vectors) do
	local v = vectors[i]
	local s = v.state
	local bytes = assert(F.Encode(s, v.max))
	local cells = "null"
	if string.len(bytes) <= F.OPTICAL_MAX then cells = ints(assert(F.ToCells(bytes)), F.NCELLS) end
	local res = {}
	for k = 1, table.getn(s.results) do
		local x = s.results[k]
		res[k] = string.format('{"name_hex":%s,"dist":%s,"flags":%d}', jstr(OV.tohex(x.name)), tostring(x.dist), x.flags)
	end
	lines[i] = string.format('    {"name":%s,"max":%s,"state":{"counter":%d,"flags":%d,"loginId":%d,"wall":%d,"ack":%d,"rosterSize":%d,' ..
		'"checked":%d,"loaded":%d,"misses":%d,"intervalMs":%d,"cost":%d,"character_hex":%s,"realm_hex":%s,"results":[%s]},' ..
		'"bytes_hex":%s,"cells":%s}',
		jstr(v.name), tostring(v.max or "null"), s.counter, s.flags, s.loginId, s.wall, s.ack, s.rosterSize, s.checked, s.loaded,
		s.misses, s.intervalMs, s.cost, jstr(OV.tohex(s.character)), jstr(OV.tohex(s.realm)), table.concat(res, ","),
		jstr(OV.tohex(bytes)), cells)
end

local f = assert(io.open(out, "wb"))
f:write('{\n  "comment": "generated by tools/gen_bridge_vectors.lua from eqvoice-addon/EqVoice/Frame.lua; do not edit",\n')
f:write(string.format('  "crc16_check": %d,\n', F.CRC16("123456789")))
f:write(string.format('  "version": %d, "cols": %d, "rows": %d, "anchor": %s, "optical_max": %d,\n', F.VERSION, F.COLS, F.ROWS, ints(F.ANCHOR, 8), F.OPTICAL_MAX))
f:write('  "vectors": [\n' .. table.concat(lines, ",\n") .. "\n  ]\n}\n")
f:close()
print("wrote " .. out .. " (" .. table.getn(vectors) .. " vectors)")
